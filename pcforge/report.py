"""A shareable plain-text health report."""
from __future__ import annotations

import time

from . import brand, toolbox
from .ai_mode import Report
from .safety import fmt_size, is_admin


def build_report(rep: Report) -> str:
    verdict = "Excellent" if rep.score >= 90 else "Good" if rep.score >= 75 else "Needs attention" if rep.score >= 50 else "Poor"
    lines = [f"{brand.NAME} health report", time.strftime("%Y-%m-%d %H:%M"), "",
             f"Health score: {rep.score}/100 ({verdict})",
             f"Run as administrator: {'yes' if is_admin() else 'no (system-wide items were skipped)'}", ""]
    lines.append("Drives")
    for d in toolbox.disk_summary():
        lines.append(f"  {d['drive']:<4} {fmt_size(d['free'])} free of {fmt_size(d['total'])} ({d['percent']:.0f}% used)")
    lines += ["", "What I would fix" if rep.steps else "Nothing needs fixing."]
    for s in rep.steps:
        lines.append(f"  +{s.impact:<3} {s.name}: {s.detail}")
    if rep.notes:
        lines += ["", "Things to know"]
        lines += [f"  - {n}" for n in rep.notes]
    lines += ["", f"Generated by {brand.NAME} {brand.VERSION}. Nothing was changed to make this report."]
    return "\n".join(lines) + "\n"
